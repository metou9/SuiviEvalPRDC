--
-- Name: v_activity_rollup; Type: VIEW; Schema: public; Owner: -
--

CREATE VIEW public.v_activity_rollup AS
 SELECT a.project_id,
    a.kind,
    a.geo_unit_id,
    gu.name AS geo_name,
    a.program_node_id,
    pn.code AS program_code,
    (EXTRACT(year FROM a.date))::integer AS period_year,
    (EXTRACT(quarter FROM a.date))::integer AS period_quarter,
    (EXTRACT(month FROM a.date))::integer AS period_month,
    count(*) AS activity_count,
    COALESCE(sum(a.total_participants), (0)::bigint) AS participants,
    COALESCE(sum(a.women_count), (0)::bigint) AS women,
    COALESCE(sum(a.youth_count), (0)::bigint) AS youth
   FROM ((public.activities_activity a
     LEFT JOIN public.geo_geounit gu ON ((gu.id = a.geo_unit_id)))
     LEFT JOIN public.program_programnode pn ON ((pn.id = a.program_node_id)))
  WHERE ((a.status)::text = 'CONSOLIDATED'::text)
  GROUP BY a.project_id, a.kind, a.geo_unit_id, gu.name, a.program_node_id, pn.code, (EXTRACT(year FROM a.date)), (EXTRACT(quarter FROM a.date)), (EXTRACT(month FROM a.date));


